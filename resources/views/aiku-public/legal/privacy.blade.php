            <div class="body">
                <p>This policy explains what data the aiku application (app.aiku.io and the sites and services it powers) collects, how it is used and the choices you have. aiku is business software operated for the companies that use it to run their shops, warehouses and customer service.</p>

                <h2>Data we collect</h2>
                <ul>
                    <li><strong>Account data:</strong> name, email address, login credentials and the permissions given to staff users.</li>
                    <li><strong>Business data:</strong> customers, orders, invoices, products, stock and messages entered into or synchronised with the application.</li>
                    <li><strong>Technical data:</strong> IP address, browser, device and usage logs, kept to secure and operate the service.</li>
                </ul>

                <h2>Google user data</h2>
                <p>When a user connects a Google account, aiku requests only the access needed for the features they turn on:</p>
                <ul>
                    <li><strong>Gmail</strong> (<code>gmail.modify</code>): to read messages in a connected shared mailbox, show them as conversations in the customer service inbox, send replies from that mailbox and mark messages as handled.</li>
                    <li><strong>Google Drive</strong> (<code>drive.readonly</code>): to open files that are linked or attached in those conversations.</li>
                    <li><strong>Google Calendar</strong> (<code>calendar.events</code>): to create and update calendar events for appointments booked in aiku.</li>
                </ul>
                <p>Google user data is used only to provide these features to the user who connected the account. It is not sold, not used for advertising, not used to train general artificial intelligence or machine learning models, and not shared with third parties except where needed to provide the service, to comply with the law, or with the user's consent. People do not read it unless the user asks for support, it is needed for security, or the law requires it.</p>
                <p>aiku's use and transfer of information received from Google APIs adheres to the <a href="https://developers.google.com/terms/api-services-user-data-policy" rel="noopener">Google API Services User Data Policy</a>, including the Limited Use requirements.</p>
                <p>You can disconnect a Google account at any time from the application or from your <a href="https://myaccount.google.com/permissions" rel="noopener">Google account permissions</a>. aiku then stops accessing it.</p>

                <h2>How we use data</h2>
                <p>Data is used to run the service, process orders and payments, provide customer support, keep the service secure, and meet legal and accounting obligations.</p>

                <h2>Sharing</h2>
                <p>Data is shared only with service providers that help run the service (hosting, email delivery, payments, shipping), under obligations to protect it, or when required by law.</p>

                <h2>Retention and deletion</h2>
                <p>Data is kept while an account is active and afterwards for as long as legal or accounting rules require. You can ask for your data to be deleted, and it will be removed unless the law requires it to be kept.</p>

                <h2>Security</h2>
                <p>Data is encrypted in transit, access is limited to authorised users, and tokens for connected accounts are stored encrypted.</p>

                <h2>Your rights</h2>
                <p>Depending on where you live, you may have the right to access, correct, export or delete your personal data, or to object to its use. Contact us to exercise these rights.</p>

                <h2>Changes</h2>
                <p>This policy may be updated. The date at the top shows the latest version.</p>

